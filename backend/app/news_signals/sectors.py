def _norm(s: str) -> str:
    return "".join(str(s).split()).lower()


_LOOKUP: dict[str, str] = {}
for _canon in SECTORS:
    _LOOKUP[_norm(_canon)] = _canon
for _canon, _aliases in ALIASES.items():
    for _a in _aliases:
        _LOOKUP.setdefault(_norm(_a), _canon)


def normalize_sector(raw: str | None) -> str | None:
    """AI 원본 섹터명을 표준 섹터로 매핑한다. 어휘에 없으면 None(특정 섹터 없음)."""
    if not raw:
        return None
    n = _norm(raw)
    if not n or n in {"null", "none", "n/a", "없음"}:
        return None
    if n in _LOOKUP:
        return _LOOKUP[n]
    for key, canon in sorted(_LOOKUP.items(), key=lambda kv: -len(kv[0])):
        if len(key) >= 2 and (key in n or n in key):
            return canon
    return None


